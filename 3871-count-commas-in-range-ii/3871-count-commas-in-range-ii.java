class Solution {
    public long countCommas(long n) {
        long comma = 0;

        if (n < 1000)
            return 0;

        if (n >= 1000L && n <= 999999L)
            comma = n - 1000L + 1;

        if (n >= 1000000L && n <= 999999999L)
            comma = 1 * (999999L - 1000L + 1)
                  + 2 * (n - 1000000L + 1);

        if (n >= 1000000000L && n <= 999999999999L)
            comma = 1 * (999999L - 1000L + 1)
                  + 2 * (999999999L - 1000000L + 1)
                  + 3 * (n - 1000000000L + 1);

        if (n >= 1000000000000L && n <= 999999999999999L)
            comma = 1 * (999999L - 1000L + 1)
                  + 2 * (999999999L - 1000000L + 1)
                  + 3 * (999999999999L - 1000000000L + 1)
                  + 4 * (n - 1000000000000L + 1);

        if (n == 1000000000000000L)
            comma = 1 * (999999L - 1000L + 1)
                  + 2 * (999999999L - 1000000L + 1)
                  + 3 * (999999999999L - 1000000000L + 1)
                  + 4 * (999999999999999L - 1000000000000L + 1)
                  + 5;

        return comma;
    }
}